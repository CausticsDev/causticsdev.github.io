#!/usr/bin/env python3
"""Scan the DEMO/ folder and write assets/js/images.js for the Caustics site.

Usage (from the site folder):   python tools/generate-images.py
Re-run it whenever you add or remove images.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent  # site folder (parent of tools/)
demo = root / "DEMO"
exts = {".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"}


def natural(p: Path):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", p.name)]


files = sorted((f for f in demo.iterdir() if f.suffix.lower() in exts), key=natural) if demo.is_dir() else []
paths = [f"DEMO/{f.name}" for f in files]

out = (
    "/* Generated by generate-images.py - run it again after adding images. */\n"
    f"window.DEMO_IMAGES = {json.dumps(paths, indent=2)};\n"
)
target = root / "assets" / "js" / "images.js"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(out, encoding="utf-8")
print(f"Wrote assets/js/images.js with {len(paths)} image(s).")
if not demo.is_dir():
    print("Note: the DEMO/ folder was not found next to this script.")
